class EmptyMosaicQueryError(Exception):
    """Exception raised when no LVF images are found in polygon.

    Parameters
    ----------
    mosaic_region: str
        Mosaic region generated by mosaic tool

    """

    def __init__(self, mosaic_region):
        self.mosaic_region = mosaic_region

    def __reduce__(self):
        # This method tells pickle how to serialize/deserialize the exception
        return (
            self.__class__,
            (self.mosaic_region,)
        )

    def __str__(self) -> str:
        return (f"No LVF images overlap with the polygon {self.mosaic_region}")
